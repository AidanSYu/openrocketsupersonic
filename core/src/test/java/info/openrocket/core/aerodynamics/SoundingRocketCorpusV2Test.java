    private static double eventTime(FlightDataBranch branch, FlightEvent.Type type) {
        FlightEvent e = branch.getFirstEvent(type);
        return e == null ? Double.NaN : e.getTime();
    }

    private static double lastEventTime(FlightDataBranch branch, FlightEvent.Type type) {
        FlightEvent e = branch.getLastEvent(type);
        return e == null ? Double.NaN : e.getTime();
    }

    private static double eventTimeAfter(FlightDataBranch branch, FlightEvent.Type type, double afterTime) {
        for (FlightEvent e : branch.getEvents()) {
            if (e.getType() == type && e.getTime() > afterTime) {
                return e.getTime();
            }
        }
        return Double.NaN;
    }

    private static void dumpEvents(FlightDataBranch branch, String label) {
        System.out.println("  [" + label + "]");
        for (FlightEvent e : branch.getEvents()) {
            System.out.printf(Locale.US, "    t=%8.3f %-22s %s%n",
                    e.getTime(), e.getType(),
                    e.getSource() == null ? "" : e.getSource().getName());
        }
    }

    private static void dumpReplacementDiagnostics(FlightData data, String vehicle) {
        if (data == null) {
            System.out.println("  [replacement-diag] " + vehicle + ": no flight data");
            return;
        }
        for (int branchIndex = 0; branchIndex < data.getBranchCount(); branchIndex++) {
            FlightDataBranch branch = data.getBranch(branchIndex);
            List<Double> times = branch.get(FlightDataType.TYPE_TIME);
            if (times == null || times.isEmpty()) {
                System.out.printf(Locale.US,
                        "  [replacement-diag] %s branch=%d name=%s has no time series%n",
                        vehicle, branchIndex, branch.getName());
                continue;
            }

            System.out.printf(Locale.US,
                    "  [replacement-diag] %s branch=%d name=%s points=%d t=[%.3f, %.3f]s%n",
                    vehicle, branchIndex, branch.getName(), branch.getLength(),
                    times.get(0), times.get(times.size() - 1));
            dumpEvents(branch, "events branch " + branchIndex + " " + branch.getName());

            Set<Integer> sampleIndices = new LinkedHashSet<>();
            sampleIndices.add(0);
            sampleIndices.add(branch.getDataIndexOfTime(0.25));
            sampleIndices.add(branch.getDataIndexOfTime(1.00));
            for (FlightEvent e : branch.getEvents()) {
                addSampleNear(branch, sampleIndices, e.getTime() - 0.10);
                addSampleNear(branch, sampleIndices, e.getTime());
                addSampleNear(branch, sampleIndices, e.getTime() + 0.10);
            }
            sampleIndices.add(maxIndex(branch, FlightDataType.TYPE_MACH_NUMBER));
            sampleIndices.add(maxIndex(branch, FlightDataType.TYPE_AOA));
            sampleIndices.add(lastFiniteIndex(branch));

            System.out.println("    t_s,alt_m,mach,thrust_N,mass_kg,motor_kg,cg_m,cp_m,stab_cal,aoa_deg,roll_dps,pitch_dps,yaw_dps,cd,cn");
            for (Integer rawIndex : sampleIndices) {
                if (rawIndex == null || rawIndex < 0 || rawIndex >= branch.getLength()) {
                    continue;
                }
                printStateRow(branch, rawIndex);
            }
        }
    }

    private static void addSampleNear(FlightDataBranch branch, Set<Integer> sampleIndices, double time) {
        if (Double.isNaN(time) || time < 0.0) {
            return;
        }
        sampleIndices.add(branch.getDataIndexOfTime(time));
    }

    private static int maxIndex(FlightDataBranch branch, FlightDataType type) {
        List<Double> values = branch.get(type);
        if (values == null || values.isEmpty()) {
            return -1;
        }
        int best = -1;
        double bestValue = -Double.MAX_VALUE;
        for (int i = 0; i < values.size(); i++) {
            double value = values.get(i);
            if (Double.isFinite(value) && value > bestValue) {
                best = i;
                bestValue = value;
            }
        }
        return best;
    }

    private static int lastFiniteIndex(FlightDataBranch branch) {
        List<Double> times = branch.get(FlightDataType.TYPE_TIME);
        if (times == null) {
            return -1;
        }
        for (int i = times.size() - 1; i >= 0; i--) {
            double time = valueAtIndex(branch, FlightDataType.TYPE_TIME, i);
            double altitude = valueAtIndex(branch, FlightDataType.TYPE_ALTITUDE, i);
            double velocity = valueAtIndex(branch, FlightDataType.TYPE_VELOCITY_TOTAL, i);
            if (Double.isFinite(time) && Double.isFinite(altitude) && Double.isFinite(velocity)) {
                return i;
            }
        }
        return -1;
    }

    private static void printStateRow(FlightDataBranch branch, int index) {
        System.out.printf(Locale.US,
                "    %.3f,%.1f,%.3f,%.1f,%.2f,%.2f,%.3f,%.3f,%.3f,%.2f,%.2f,%.2f,%.2f,%.3f,%.3f%n",
                valueAtIndex(branch, FlightDataType.TYPE_TIME, index),
                valueAtIndex(branch, FlightDataType.TYPE_ALTITUDE, index),
                valueAtIndex(branch, FlightDataType.TYPE_MACH_NUMBER, index),
                valueAtIndex(branch, FlightDataType.TYPE_THRUST_FORCE, index),
                valueAtIndex(branch, FlightDataType.TYPE_MASS, index),
                valueAtIndex(branch, FlightDataType.TYPE_MOTOR_MASS, index),
                valueAtIndex(branch, FlightDataType.TYPE_CG_LOCATION, index),
                valueAtIndex(branch, FlightDataType.TYPE_CP_LOCATION, index),
                valueAtIndex(branch, FlightDataType.TYPE_STABILITY, index),
                Math.toDegrees(valueAtIndex(branch, FlightDataType.TYPE_AOA, index)),
                Math.toDegrees(valueAtIndex(branch, FlightDataType.TYPE_ROLL_RATE, index)),
                Math.toDegrees(valueAtIndex(branch, FlightDataType.TYPE_PITCH_RATE, index)),
                Math.toDegrees(valueAtIndex(branch, FlightDataType.TYPE_YAW_RATE, index)),
                valueAtIndex(branch, FlightDataType.TYPE_DRAG_COEFF, index),
                valueAtIndex(branch, FlightDataType.TYPE_NORMAL_FORCE_COEFF, index));
    }

    private static double valueAtIndex(FlightDataBranch branch, FlightDataType type, int index) {
        if (index < 0 || index >= branch.getLength()) {
            return Double.NaN;
        }
        List<Double> values = branch.get(type);
        if (values == null || index >= values.size()) {
            return Double.NaN;
        }
        return values.get(index);
    }

    private static double valueAtTime(FlightDataBranch branch, FlightDataType type, double t) {
        if (Double.isNaN(t)) return Double.NaN;
        java.util.List<Double> times = branch.get(FlightDataType.TYPE_TIME);
        java.util.List<Double> values = branch.get(type);
        if (times == null || values == null || times.isEmpty()) return Double.NaN;
        int idx = 0;
        for (int i = 0; i < times.size() - 1; i++) {
            if (times.get(i) <= t && times.get(i + 1) >= t) { idx = i; break; }
        }
        if (idx + 1 >= times.size()) return values.get(values.size() - 1);
        double t0 = times.get(idx), t1 = times.get(idx + 1);
        double v0 = values.get(idx), v1 = values.get(idx + 1);
        if (t1 == t0) return v0;
        return v0 + (v1 - v0) * (t - t0) / (t1 - t0);
    }

    private static void verifyRow(String label, double spec, double model) {
        double diffPct = (model - spec) / spec * 100.0;
        System.out.printf(Locale.US, "  %-30s %-20.3f %-20.3f %+.2f%%%n",
                label, spec, model, diffPct);
    }

    private static File findDir(String relativePath) {
        File dir = new File(relativePath);
        if (dir.exists()) return dir;
        Path current = Paths.get(System.getProperty("user.dir"));
        for (int i = 0; i < 6 && current != null; i++) {
            File candidate = current.resolve(relativePath).toFile();
            if (candidate.exists()) return candidate;
            current = current.getParent();
        }
        return null;
    }

