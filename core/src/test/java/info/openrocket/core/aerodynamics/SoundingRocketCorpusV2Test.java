    private static Row simulate(File ork, String vehicle, double apogeeRealFt, String sourceDoc,
                                double launchAngleFromVerticalDeg, double launchAltitudeM,
                                double exitSpinRateRevPerSec, double maxSimulationTimeS,
                                long wallTimeoutMs, double timeStepS, double maxStepAngleDeg,
                                boolean ascentOnly)
            throws Exception {
        if (!ork.exists()) {
            return new Row(vehicle, sourceDoc, apogeeRealFt, Double.NaN,
                    "ORK FILE MISSING: " + ork.getAbsolutePath());
        }
        try {
            GeneralRocketLoader loader = new GeneralRocketLoader(ork);
            OpenRocketDocument doc = loader.load();

            // Force-activate the default flight configuration. The .ork builder
            // declares motorconfiguration with stage activations, but the
            // selected configuration on Rocket may default to the empty
            // configuration; explicitly select the first non-empty config so
            // hasMotors() returns true.
            info.openrocket.core.rocketcomponent.Rocket rocket = doc.getRocket();
            for (info.openrocket.core.rocketcomponent.FlightConfigurationId fcid : rocket.getIds()) {
                if (fcid != null && rocket.getFlightConfiguration(fcid).hasMotors()) {
                    rocket.setSelectedConfiguration(fcid);
                    break;
                }
            }
            // Ensure all stages are active in the selected configuration.
            rocket.getSelectedConfiguration().setAllStages();

            List<Simulation> sims = doc.getSimulations();
            Simulation sim;
            if (sims.isEmpty()) {
                sim = new Simulation(doc, rocket);
                doc.addSimulation(sim);
            } else {
                sim = sims.get(0);
            }
            // Bind the simulation to the configured selection, in case the
            // newly-created Simulation defaulted to the empty configuration.
            sim.setFlightConfigurationId(rocket.getSelectedConfiguration().getFlightConfigurationID());
            // 0.02 s step — coarse but ~2x faster than 0.01 s and still
            // numerically stable under ~80 g peak accel with the spin-
            // injected gyroscopic stabilization. 0.05 s default crashes
            // the integrator; 0.005 s timed out (>180 s real time).
            // Per user direction: prioritize runtime over fine resolution.
            sim.getOptions().setTimeStep(timeStepS);
            sim.getOptions().setMaximumStepAngle(Math.toRadians(maxStepAngleDeg));
            // We only need ascent/apogee for corpus validation. Letting these
            // vehicles continue through long descent/re-entry frequently burns
            // minutes of CPU and can diverge after the metric of interest is
            // already captured.
            sim.getOptions().setMaxSimulationTime(maxSimulationTimeS);
            sim.getOptions().setRandomSeed(0x51A7EA);
            sim.getOptions().setLaunchRodAngle(Math.toRadians(launchAngleFromVerticalDeg));
            sim.getOptions().setLaunchAltitude(launchAltitudeM);

            final LaunchSpinListener spinListener =
                    new LaunchSpinListener(exitSpinRateRevPerSec * 2.0 * Math.PI);
            final ApogeeCutoffListener apogeeCutoff = new ApogeeCutoffListener(ascentOnly);

            // Run with a generous timeout (sounding rockets descend slowly from 100+ km).
            final Throwable[] simErr = new Throwable[1];
            Thread t = new Thread(() -> {
                try {
                    sim.simulate(spinListener, apogeeCutoff);
                } catch (Throwable th) {
                    simErr[0] = th;
                }
            });
            t.start();
            t.join(wallTimeoutMs);
            if (t.isAlive()) {
                t.interrupt();
                return new Row(vehicle, sourceDoc, apogeeRealFt, Double.NaN,
                        "TIMEOUT after " + (wallTimeoutMs / 1000) + "s");
            }
            if (simErr[0] != null) {
                FlightData partial = sim.getSimulatedData();
                boolean intentionalCutoff = simErr[0].getMessage() != null
                        && simErr[0].getMessage().contains(ApogeeCutoffListener.MARKER);
                if (partial != null && partial.getBranchCount() > 0) {
                    double partialApogeeM = partial.getMaxAltitude();
                    double partialApogeeFt = partialApogeeM * 3.28084;
                    String diagLabel = intentionalCutoff ? "ascent-cutoff" : "crash-diag";
                    System.out.printf(Locale.US,
                            "  [%s] %s: maxAlt=%.0fm (%.0f ft), maxMach=%.3f, "
                                    + "maxVel=%.1f m/s, flightTime=%.2fs, branches=%d, "
                                    + "spinInjected=%b @ t=%.4fs, ERR=%s%n",
                            diagLabel,
                            vehicle, partialApogeeM, partialApogeeFt,
                            partial.getMaxMachNumber(), partial.getMaxVelocity(),
                            partial.getFlightTime(), partial.getBranchCount(),
                            spinListener.injected, spinListener.injectionTime,
                            simErr[0].getMessage());
                    if (!intentionalCutoff) {
                        dumpReplacementDiagnostics(partial, vehicle);
                    }
                    // If we hit the apogee cutoff (intentional ascent-only
                    // truncation), or the integrator NaN'd during descent but
                    // we already captured a substantial apogee (>1 km, > 10%
                    // of target), use the partial result — apogee is the
                    // only validation metric.
                    if (Double.isFinite(partialApogeeM) && partialApogeeM > 1000.0
                            && partialApogeeFt > apogeeRealFt * 0.10) {
                        String note = intentionalCutoff
                                ? "ASCENT-ONLY-CUTOFF (apogee captured)"
                                : "DESCENT-NAN (apogee captured): " + simErr[0].getMessage();
                        return new Row(vehicle, sourceDoc, apogeeRealFt,
                                partialApogeeFt,
                                partial.getMaxMachNumber(),
                                partial.getMaxVelocity(),
                                partial.getMaxAcceleration(),
                                partial.getFlightTime(),
                                note);
                    }
                }
                return new Row(vehicle, sourceDoc, apogeeRealFt, Double.NaN,
                        "SIM ERROR: " + simErr[0].getMessage());
            }
            FlightData data = sim.getSimulatedData();
            if (data == null || data.getBranchCount() == 0) {
                return new Row(vehicle, sourceDoc, apogeeRealFt, Double.NaN,
                        "NO FLIGHT DATA");
            }
            double apogeeFt = data.getMaxAltitude() * 3.28084;

            // Print full flight summary on stdout regardless of apogee outcome.
            // We need this to distinguish foundation-modeling failures (peak
            // Mach reached but drag too high) from .ork construction failures
            // (motor binds but rocket never accelerates, or NaN propagates).
            String warns = sim.getSimulatedWarnings() != null
                    ? sim.getSimulatedWarnings().toString().replace("\n", " | ")
                    : "(none)";
            System.out.printf(Locale.US,
                    "  [diag] %s: maxAlt=%.0fm (%.0f ft), maxMach=%.3f, maxVel=%.1f m/s, "
                            + "maxAccel=%.1f m/s^2, flightTime=%.1fs, branches=%d, "
                            + "spinInjected=%b @ t=%.3fs%n",
                    vehicle, data.getMaxAltitude(), apogeeFt,
                    data.getMaxMachNumber(), data.getMaxVelocity(),
                    data.getMaxAcceleration(), data.getFlightTime(),
                    data.getBranchCount(),
                    spinListener.injected, spinListener.injectionTime);
            if (!"(none)".equals(warns) && !warns.equals("[]")) {
                System.out.printf(Locale.US, "  [warn] %s: %s%n", vehicle,
                        warns.length() > 600 ? warns.substring(0, 600) + "..." : warns);
            }
            dumpReplacementDiagnostics(data, vehicle);

            String diagnostic = "";
            if (apogeeFt < 1.0) {
                boolean hasMotors = doc.getRocket().getSelectedConfiguration().hasMotors();
                diagnostic = String.format(Locale.US,
                        "ZERO APOGEE: maxAlt=%.3fm, branches=%d, hasMotors=%b, flightTime=%.1fs, warnings=%s",
                        data.getMaxAltitude(), data.getBranchCount(),
                        hasMotors, data.getFlightTime(),
                        warns.length() > 200 ? warns.substring(0, 200) + "..." : warns);
            }
            return new Row(vehicle, sourceDoc, apogeeRealFt, apogeeFt,
                    data.getMaxMachNumber(), data.getMaxVelocity(),
                    data.getMaxAcceleration(), data.getFlightTime(), diagnostic);
        } catch (Throwable th) {
            return new Row(vehicle, sourceDoc, apogeeRealFt, Double.NaN,
                    "LOAD ERROR: " + th.getClass().getSimpleName() + ": " + th.getMessage());
        }
    }

